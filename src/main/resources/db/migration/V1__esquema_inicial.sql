-- Tabla del catalogo tal como la creaba Hibernate en la primera version de la aplicacion.
-- IF NOT EXISTS: las bases anteriores a las migraciones ya la tienen y deben pasar por aqui sin cambios.
CREATE TABLE IF NOT EXISTS laptop (
    id integer,
    battery_wh float,
    brand varchar(40) not null,
    category varchar(30) not null,
    chassis_material varchar(60),
    color_hex varchar(7),
    cpu varchar(80) not null,
    cpu_base_watts integer check (cpu_base_watts>=0),
    cpu_boost_watts integer check (cpu_boost_watts>=0),
    cpu_cores integer check (cpu_cores>=1),
    depth_mm float,
    gpu varchar(80) not null,
    gpu_tgp_watts integer check (gpu_tgp_watts>=0),
    gpu_vram_gb integer check (gpu_vram_gb>=0),
    image_url varchar(300),
    model varchar(80) not null,
    notes varchar(400),
    panel_type varchar(40),
    ram_gb integer check (ram_gb>=1),
    ram_type varchar(40),
    ram_upgradable boolean,
    refresh_rate_hz integer check (refresh_rate_hz>=0),
    resolution varchar(20),
    screen_inches float,
    source_url varchar(300),
    storage_gb integer check (storage_gb>=1),
    storage_slots integer check (storage_slots>=0),
    thickness_mm float,
    weight_kg float,
    width_mm float,
    primary key (id)
);
